--------------------------------------------------------
-- 8) Oracle Native Unified Audit policies (run as DBA)
--------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE AUDIT POLICY cg_audit_orders_payments
            ACTIONS UPDATE ON "CARDGAME"."ORDERS",
                    INSERT ON "CARDGAME"."PAYMENTS",
                    UPDATE ON "CARDGAME"."PAYMENTS"
    ]';
EXCEPTION
    WHEN OTHERS THEN
        -- ORA-46377: policy already exists
        -- ORA-01031: insufficient privileges
        IF SQLCODE NOT IN (-46377, -1031) THEN
            RAISE;
        END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'AUDIT POLICY cg_audit_orders_payments';
EXCEPTION
    WHEN OTHERS THEN
