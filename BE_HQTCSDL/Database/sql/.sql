-- 0) Safe helper for GRANT statements
--------------------------------------------------------
CREATE OR REPLACE PROCEDURE "CARDGAME"."SP_SAFE_GRANT"
(
    p_sql IN VARCHAR2
)
IS
BEGIN
    EXECUTE IMMEDIATE p_sql;
EXCEPTION
    WHEN OTHERS THEN
        -- Ignore: user/role does not exist, insufficient privilege, duplicate grant
        IF SQLCODE NOT IN (-1917, -1919, -1921, -1031) THEN
            RAISE;
        END IF;
END;
/

