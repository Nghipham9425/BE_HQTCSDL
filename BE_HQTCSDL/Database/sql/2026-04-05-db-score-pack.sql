CREATE OR REPLACE PROCEDURE "CARDGAME"."SP_UPSERT_PAYMENT" (
    p_order_id          IN NUMBER,
    p_payment_method_id IN NUMBER,
    p_amount            IN NUMBER,
    p_status            IN VARCHAR2,
    p_transaction_id    IN VARCHAR2
)
IS
    v_id NUMBER;
BEGIN
    SELECT "ID"
      INTO v_id
      FROM "CARDGAME"."PAYMENTS"
     WHERE "ORDER_ID" = p_order_id
       AND ROWNUM = 1;

    UPDATE "CARDGAME"."PAYMENTS"
       SET "PAYMENT_METHOD_ID" = p_payment_method_id,
           "AMOUNT" = p_amount,
           "STATUS" = p_status,
           "TRANSACTION_ID" = p_transaction_id
     WHERE "ID" = v_id;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        INSERT INTO "CARDGAME"."PAYMENTS" (
            "ORDER_ID", "PAYMENT_METHOD_ID", "AMOUNT", "STATUS", "TRANSACTION_ID"
        ) VALUES (
            p_order_id, p_payment_method_id, p_amount, p_status, p_transaction_id
        );
END;
/

