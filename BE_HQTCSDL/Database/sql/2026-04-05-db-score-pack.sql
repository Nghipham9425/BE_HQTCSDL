CREATE OR REPLACE FUNCTION "CARDGAME"."FN_ORDER_TOTAL" (
    p_order_id IN NUMBER
) RETURN NUMBER
IS
    v_total NUMBER := 0;
BEGIN
    SELECT NVL(SUM(NVL("PRICE", 0) * NVL("QUANTITY", 0)), 0)
      INTO v_total
      FROM "CARDGAME"."ORDER_DETAILS"
     WHERE "ORDER_ID" = p_order_id;

    RETURN v_total;
END;
