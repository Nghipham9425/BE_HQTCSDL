-- Normalize legacy statuses before adding CHECK constraints.
UPDATE "CARDGAME"."ORDERS"
   SET "ORDER_STATUS" = CASE
        WHEN "ORDER_STATUS" IS NULL THEN 'PENDING'
        WHEN UPPER(TRIM("ORDER_STATUS")) IN ('PENDING', 'CONFIRMED', 'SHIPPING', 'COMPLETED', 'CANCELLED')
            THEN UPPER(TRIM("ORDER_STATUS"))
        WHEN UPPER(TRIM("ORDER_STATUS")) IN ('SHIPPED', 'DELIVERING') THEN 'SHIPPING'
        WHEN UPPER(TRIM("ORDER_STATUS")) IN ('DONE', 'SUCCESS') THEN 'COMPLETED'
        WHEN UPPER(TRIM("ORDER_STATUS")) IN ('CANCELED', 'CANCEL', 'FAILED', 'ERROR') THEN 'CANCELLED'
        ELSE 'PENDING'
   END;

UPDATE "CARDGAME"."PAYMENTS"
   SET "STATUS" = CASE
        WHEN "STATUS" IS NULL THEN 'PENDING'
        WHEN UPPER(TRIM("STATUS")) IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')
            THEN UPPER(TRIM("STATUS"))
        WHEN UPPER(TRIM("STATUS")) IN ('SUCCESS', 'COMPLETED') THEN 'PAID'
        WHEN UPPER(TRIM("STATUS")) IN ('CANCELED', 'CANCEL', 'ERROR') THEN 'CANCELLED'
        ELSE 'PENDING'
   END;

COMMIT;

