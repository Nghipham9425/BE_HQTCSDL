CREATE OR REPLACE PROCEDURE "CARDGAME"."SP_BACKUP_ORDERS" (
    p_from_date IN DATE,
    p_to_date   IN DATE
)
IS
BEGIN
    INSERT INTO "CARDGAME"."ORDERS_BACKUP" (
        "ORDER_ID", "CUSTOMER_ID", "AMOUNT", "DISCOUNT_AMOUNT", "SHIPPING_ADDRESS",
        "ORDER_EMAIL", "NOTE", "PAYMENT_METHOD_ID", "ORDER_DATE", "ORDER_STATUS"
    )
    SELECT "ID", "CUSTOMER_ID", "AMOUNT", "DISCOUNT_AMOUNT", "SHIPPING_ADDRESS",
           "ORDER_EMAIL", "NOTE", "PAYMENT_METHOD_ID", "ORDER_DATE", "ORDER_STATUS"
      FROM "CARDGAME"."ORDERS"
     WHERE "ORDER_DATE" >= TRUNC(p_from_date)
       AND "ORDER_DATE" < TRUNC(p_to_date) + 1;
END;
